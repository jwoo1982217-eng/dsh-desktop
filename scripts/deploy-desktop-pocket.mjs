import { homedir as __publicHomedir } from 'node:os';
import {readFile,writeFile,mkdir,cp,realpath} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';
import path from 'node:path';
import {patchPocket} from '../runtime/pocket-update/patch.mjs';
import {performDesktopUpdate} from '../runtime/pocket-update/adapter.mjs';

const report=path.resolve(process.argv[2]),apply=process.argv.includes('--apply');
const app='/Applications/DSH.app',resources=path.join(app,'Contents/Resources');
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const require=createRequire(new URL('../desktop/macos/tools/package.json',import.meta.url)),asar=require('@electron/asar');
const staged=path.join(report,'app-stage'),archive=path.join(resources,'app.asar');
await mkdir(staged,{recursive:true,mode:0o700});
const original=await readFile(archive),backend=asar.extractFile(archive,'backend.mjs').toString();
const nextBackend=await readFile('desktop/macos/app/backend.mjs','utf8');
const expected=nextBackend.replace("import {preservePocket} from './pocket-preserve.mjs';\n",'').replace("      if (name === 'dsh-pocket' && await preservePocket(home, profile, modules, manifest)) continue;\n",'');
if(backend!==expected&&!backend.includes('preservePocket'))throw Error('桌面应用已有其他 backend 修改，未覆盖');
asar.extractAll(archive,staged);
await cp('desktop/macos/app/backend.mjs',path.join(staged,'backend.mjs'));
await cp('desktop/macos/app/pocket-preserve.mjs',path.join(staged,'pocket-preserve.mjs'));
const candidate=path.join(report,'app-adapted.asar');await asar.createPackage(staged,candidate);
const integrity=hash(asar.getRawHeader(candidate).headerString);
const plan={archiveBefore:hash(original),archiveAfter:hash(await readFile(candidate)),integrity,app,coreRestarted:false};
await writeFile(path.join(report,'deployment-plan.json'),JSON.stringify(plan,null,2));
if(!apply){console.log(JSON.stringify({...plan,prepared:true}));process.exit(0);}
execFileSync('/usr/bin/codesign',['--verify','--deep','--strict',app]);
const backup=path.join(report,'before-live');await mkdir(backup,{recursive:true,mode:0o700});
console.log('Backing up installed application and Pocket before deployment');
execFileSync('/bin/cp',['-cR',app,path.join(backup,'DSH.app')]);
const home=(__publicHomedir() + '/.dsh'),profile=path.join(home,'profiles/web'),target=path.join(profile,'node_modules/dsh-pocket');
await cp(target,path.join(backup,'profile-pocket'),{recursive:true});
await cp(path.join(profile,'package.json'),path.join(backup,'profile-package.json'));
const protectedFiles=[path.join(home,'.credentials.yaml'),path.join(home,'cordis.patch.yml'),path.join(profile,'cordis.patch.yml'),path.join(home,'dsh-pocket/settings.json'),path.join(home,'dsh-pocket/token'),path.join(home,'dsh-pocket/token-lan')];
const before=Object.fromEntries(await Promise.all(protectedFiles.map(async f=>[f,hash(await readFile(f))])));
if(hash(await readFile(archive))!==plan.archiveBefore)throw Error('桌面应用在部署前变化，未覆盖');
await patchPocket(await realpath(path.resolve('desktop-runtime/node_modules/dsh-pocket')));
await patchPocket(await realpath(path.join(resources,'runtime/node_modules/dsh-pocket')));
await cp(candidate,archive);
execFileSync('/usr/libexec/PlistBuddy',['-c',`Set :ElectronAsarIntegrity:Resources/app.asar:hash ${integrity}`,path.join(app,'Contents/Info.plist')]);
execFileSync('/usr/bin/codesign',['--force','--deep','--sign','-','--preserve-metadata=entitlements,requirements,flags',app],{stdio:'pipe'});
execFileSync('/usr/bin/codesign',['--verify','--deep','--strict',app]);
console.log('Application adaptation signed and verified; staging Pocket 2.12.0');
const result=await performDesktopUpdate({home,profile:'web',packageDirectory:target,coreEntry:path.resolve('desktop-runtime/node_modules/@deepseek-ai/dsh/lib/bin.js')});
const after=Object.fromEntries(await Promise.all(protectedFiles.map(async f=>[f,hash(await readFile(f))])));
const receipt={...plan,result,protectedFilesUnchanged:JSON.stringify(before)===JSON.stringify(after),backup,activation:'next safe DSH service restart'};
await writeFile(path.join(report,'live-deployment.json'),JSON.stringify(receipt,null,2),{mode:0o600});
console.log(JSON.stringify(receipt));
if(!result.ok||!receipt.protectedFilesUnchanged)process.exitCode=1;
