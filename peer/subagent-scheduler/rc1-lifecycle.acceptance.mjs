import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {Context, symbols} from '@deepseek-ai/cordis';
import Sessions from '@deepseek-ai/dsh-session';
import Projections from '@deepseek-ai/dsh-session-projection';
import Agents from '@deepseek-ai/dsh-agent';
import SystemPrompt from '@deepseek-ai/dsh-system-prompt';
import Tools from '@deepseek-ai/dsh-tools';
import Subagents from '@deepseek-ai/dsh-subagent';
import Settings from '@deepseek-ai/dsh-tool-subagent/model-selection-settings';
import Llm from '@deepseek-ai/dsh-llm';
import LocalFs from '@deepseek-ai/dsh-fs-local';
import WorkingDirectory from '@deepseek-ai/dsh-working-directory';
import * as Scheduler from './index.mjs';

test('rc1 unloading scheduler restores exact live native methods and closes queue ownership', async t => {
  assert.ok(path.isAbsolute(process.env.DSH_ACCEPTANCE_ROOT));
  const home = fs.mkdtempSync(path.join(process.env.DSH_ACCEPTANCE_ROOT, 'scheduler-lifecycle-'));
  const previous = process.env.DSH_HOME; process.env.DSH_HOME = home;
  const ctx = new Context();
  t.after(async () => { await ctx.fiber.dispose(); fs.rmSync(home, {recursive: true, force: true}); if (previous === undefined) delete process.env.DSH_HOME; else process.env.DSH_HOME = previous; });
  ctx.provide('connection', {rpc: {handle() {}}, requestRejection() {}});
  ctx.provide('webServer', {register() { return () => {}; }});
  for (const plugin of [Llm, Sessions, Projections, Agents, SystemPrompt, Tools, LocalFs]) await ctx.plugin(plugin);
  await ctx.plugin(WorkingDirectory, {defaultDirectory: home});
  await ctx.plugin(Subagents);
  await ctx.plugin(Settings, {enabled: false, allowedModels: []});
  const raw = ctx.subagents[symbols.original], start = raw.startActivation, send = raw.sendMessage;
  const fork = ctx.plugin(Scheduler); await fork;
  const scheduler = ctx.get('dshSubagentScheduler');
  assert.notEqual(raw.startActivation, start);
  assert.notEqual(raw.sendMessage, send);
  assert.equal(scheduler.closed, false);
  await fork.dispose();
  assert.equal(raw.startActivation, start);
  assert.equal(raw.sendMessage, send);
  assert.equal(scheduler.closed, true);
  assert.equal(ctx.get('dshSubagentScheduler'), undefined);
});
